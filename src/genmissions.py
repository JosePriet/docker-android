# v21: faction mission chains (ChatGPT-authored text in src/data) -> ModFactionData.java
#   python3 -I src/genmissions.py src/data src/java/fr/testudo/spacecorsair/mod/ModFactionData.java
import json, re, sys
D, OUT = sys.argv[1], sys.argv[2]
missions = json.load(open(D + '/faction_missions.json'))
md = open(D + '/factions.md').read()
ORDER = ['spartan', 'reaver', 'kretari', 'varn', 'ironclad', 'helion', 'warden']
HEAD = {'Spartan Republic': 'spartan', 'Crimson Reavers': 'reaver', "Kre'tari Brood": 'kretari', 'Varn Syndicate': 'varn',
        'Ironclad Militia': 'ironclad', 'Helion Combine': 'helion', 'Frontier Authority': 'warden'}
commander, flagdesc = {}, {}
for sec in re.split(r'\n## ', md)[1:]:
    title = sec.split('\n', 1)[0].strip()
    k = HEAD[title]
    m = re.search(r'\*\*Commander\s*[—-]\s*([^:*]+):\*\*\s*(.+)', sec)
    commander[k] = (m.group(1).strip(), m.group(2).strip())
    f = re.search(r'\*\*Flagship\s*[—-]\s*[^:*]+:\*\*\s*(.+)', sec)
    flagdesc[k] = f.group(1).strip()
FAM = {'railgun': 'modRailgun', 'autocannon': 'modAutocannon', 'artillery': 'modArtillery', 'blaster': 'modBlaster',
       'disintegrator': 'modDisintegrator', 'arc projector': 'modArcProjector'}
TIER = {'light': '', 'standard': 'L5', 'heavy': 'L10', 'siege': 'L15'}


def reward(h):
    m = re.match(r'\s*([\d.]+)\s*([kKmM])?\s*credits\s*\+\s*(\w+)\s+(.+?)\s*$', h)
    n = float(m.group(1)) * {'k': 1e3, 'm': 1e6, None: 1}[m.group(2).lower() if m.group(2) else None]
    return int(n), FAM[m.group(4).lower()] + TIER[m.group(3).lower()]


def js(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


# objective details the game needs that the text leaves open (counts, extra sectors, targets)
EXTRA = {('varn', 1): 'THE_VAULT'}   # the sealed crate is collected in The Vault, then handed in at Omicron Prime
rows = []
for k in ORDER:
    for m in sorted([x for x in missions if x['faction'] == k], key=lambda x: x['order']):
        cr, item = reward(m['reward_hint'])
        nums = re.findall(r'\b(\d+)\b', m['objective_details'])
        count = int(nums[0]) if nums else 0
        sector = EXTRA.get((k, m['order']), m['sector'])
        tgt = ''
        t = re.search(r'Destroy (SRS Aegis|FAV Warden|Bloodforge|Syndicate Crown|IMS Bastion|Sunspire|Brood-Mother)', m['objective_details'])
        if t: tgt = {'SRS Aegis': 'spartan', 'FAV Warden': 'warden', 'Bloodforge': 'reaver', 'Syndicate Crown': 'varn',
                     'IMS Bastion': 'ironclad', 'Sunspire': 'helion', 'Brood-Mother': 'kretari'}[t.group(1)]
        if m['objective'] == 'DEFEND_ZONE': tgt = k
        name = ''
        n = re.search(r'(?:courier|raider) (\w+)', m['objective_details'])
        if n: name = n.group(1)
        dest = ''
        d2 = re.search(r'from \w+ to (\w+)', m['objective_details'])
        if d2: dest = d2.group(1)
        details = re.sub(r'\b[A-Z]{3,}(?:_[A-Z]+)*\b', lambda x: x.group(0).replace('_', ' ').title(), m['objective_details'])
        rows.append([k, m['order'], m['title'], m['objective'], sector, m['sector'], m['min_level'], count, tgt, name, dest,
                     m['briefing'], details, m['success'], m['failure'], cr, item])
j = ['package fr.testudo.spacecorsair.mod;', '',
     '/** Generated by src/genmissions.py from src/data (faction_missions.json, factions.md). Do not edit. */',
     'final class ModFactionData {', '    private ModFactionData() {}', '',
     '    static final String[] KEYS = {' + ', '.join(js(k) for k in ORDER) + '};',
     '    static final String[] COMMANDER = {' + ', '.join(js(commander[k][0]) for k in ORDER) + '};',
     '    static final String[] COMMANDER_LINE = {' + ', '.join(js(commander[k][1]) for k in ORDER) + '};',
     '    static final String[] FLAGSHIP_DESC = {' + ', '.join(js(flagdesc[k]) for k in ORDER) + '};', '',
     '    // faction, order, title, objective, objective sector, hand-in sector, min level, count, flagship key, target name, destination,',
     '    // briefing, details, success, failure, credits, reward item',
     '    static final Object[][] MISSIONS = {']
for r in rows:
    j.append('        {' + ', '.join(js(v) if isinstance(v, str) else str(v) for v in r) + '},')
j += ['    };', '}', '']
open(OUT, 'w').write('\n'.join(j))
for r in rows: print(r[0], r[1], r[3], r[4], r[5], 'count', r[7], 'tgt', r[8], 'name', r[9], 'dest', r[10], r[15], r[16])
