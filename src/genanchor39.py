# v39: bakes the Leviathan anchor-stance shield wall from the approved preview (leviathan-vfx/anchor.py, owner 2026-11-03).
#   python3 -I src/genanchor39.py work/modart
# Writes work/modart/lev_anchor_wall.webp: the hex wall arc (white + alpha, additive tint in game), 1 px = 1 unit of the
# 1024 px hull sprite, and src/java/.../ModAnchorData.java: the canvas placement in hull-sprite units (+y = stern).
# Geometry = preview scaled x2 (preview sprite 512 px): arc radius R 660 around the hull centre, thickness 48, +-48 deg,
# pointy hex cells s 22.
import os, sys
import numpy as np
from PIL import Image

ART = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
R = 660.0; TH = 48.0; SPAN = np.radians(48); S = 22.0; PADG = 40
x_max = R * np.sin(SPAN + 0.06) + PADG
y_top = -(R + TH / 2 + PADG)                       # prow side (local y up = negative)
y_bot = -R * np.cos(SPAN + 0.06) + TH / 2 + PADG
W = int(np.ceil(2 * x_max)); H = int(np.ceil(y_bot - y_top))
W += W % 2; H += H % 2
X, Y = np.mgrid[:H, :W][::-1].astype(float)
X = X + 0.5 - W / 2; Y = Y + 0.5 + y_top            # hull-local coords (centre = 0, 0)
dr = np.hypot(X, Y); th = np.arctan2(X, -Y)           # 0 = straight ahead
u = R * th; v = dr - R
band = np.exp(-(np.clip(np.abs(v) - TH / 2, 0, None) / 4.0) ** 2)
qf = (np.sqrt(3) / 3 * u - 1 / 3 * v) / S; rf = (2 / 3 * v) / S


def cube_round(q, r_):
    x_ = q; z_ = r_; y_ = -x_ - z_; rx, ry, rz = np.round(x_), np.round(y_), np.round(z_)
    dx, dy, dz = np.abs(rx - x_), np.abs(ry - y_), np.abs(rz - z_)
    m1 = (dx > dy) & (dx > dz); m2 = (~m1) & (dy > dz)
    rx = np.where(m1, -ry - rz, rx); ry = np.where(m2, -rx - rz, ry); rz = -rx - ry
    return rx, rz


hq, hr = cube_round(qf, rf)
cu = S * np.sqrt(3) * (hq + hr / 2); cv = S * 1.5 * hr
dcell = np.hypot(u - cu, v - cv) / S
hexedge = np.clip((dcell - 0.62) / 0.3, 0, 1) ** 1.5
cell_rand = (np.sin(hq * 12.9898 + hr * 78.233) * 43758.5453) % 1.0
uf = np.abs(th) / SPAN
ends = np.clip((1.0 - uf) / 0.06, 0, 1)               # soft wall ends
core = band * ends * (np.abs(v) < TH / 2 + 2)
# preview look: faint cell fill + bright hex edges + a thin bright rim on both faces + soft outer glow
rim = np.exp(-((np.abs(v) - TH / 2) / 1.6) ** 2) * ends * (uf < 1.0)
glow = np.exp(-np.clip(np.abs(v) - TH / 2, 0, None) / 14.0) * ends * (uf < 1.02) * 0.35
al = np.clip(core * (0.16 + 0.10 * cell_rand + 0.75 * hexedge) + rim * 0.7 + glow, 0, 1)
im = Image.fromarray((al * 255).astype(np.uint8), 'L')
Image.merge('RGBA', (Image.new('L', im.size, 255),) * 3 + (im,)).save(
    os.path.join(ART, 'lev_anchor_wall.webp'), 'WEBP', lossless=True, quality=100, method=6, exact=True)

java = '''package fr.testudo.spacecorsair.mod;

/** Generated by src/genanchor39.py (v39): Leviathan anchor wall texture placement, 1024 px hull-sprite units (+y = stern). */
final class ModAnchorData {
    private ModAnchorData() {}

    /** Texture lev_anchor_wall: W x H px, centred on x 0, top edge at Y_TOP (prow side). */
    static final float W = %df, H = %df, Y_TOP = %sf;
    /** Arc radius around the hull centre, thickness, half-span (deg). */
    static final float R = %sf, TH = %sf, SPAN_DEG = 48f;
}
''' % (W, H, round(y_top, 2), R, TH)
open(os.path.join(HERE, 'java/fr/testudo/spacecorsair/mod/ModAnchorData.java'), 'w').write(java)
print('ok', W, H, round(y_top, 1), round(y_bot, 1))
