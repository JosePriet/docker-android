# v39: bakes the Leviathan anchor-stance shield wall from the approved preview (leviathan-vfx/anchor.py, owner 2026-11-03).
#   python3 -I src/genanchor39.py work/modart
# Owner 2026-11-03 14:35: the wall covers 240 deg. It is drawn in game as 16 rotated copies of one 15-degree wedge of the hex
# band (the hex period divides the wedge's arc length, so the copies join seamlessly), plus an end wedge that fades out.
# Writes work/modart/lev_anchor_seg.webp, lev_anchor_end.webp (white + alpha, additive tint in game; 1 px = 1 unit of the
# 1024 px hull sprite) and src/java/.../ModAnchorData.java (placement in hull-sprite units, +y = stern).
# Geometry = preview x2: arc radius R 660 around the hull centre, thickness 48, pointy hex cells (s 19.95 so 5 periods fill a wedge).
import os, sys
import numpy as np
from PIL import Image

ART = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
R = 660.0; TH = 48.0; SEG = 15.0; NSEG = 16; PADG = 30
S = R * np.radians(SEG) / (5 * np.sqrt(3))
half = np.radians(SEG / 2)
ro, ri = R + TH / 2 + PADG, R - TH / 2 - PADG
x_max = ro * np.sin(half) + 2
y_top = -ro - 1
y_bot = -ri * np.cos(half) + 1
W = int(np.ceil(2 * x_max)); H = int(np.ceil(y_bot - y_top))
W += W % 2; H += H % 2
X, Y = np.mgrid[:H, :W][::-1].astype(float)
X = X + 0.5 - W / 2; Y = Y + 0.5 + y_top
dr = np.hypot(X, Y); th = np.arctan2(X, -Y)
u = R * th; v = dr - R
band = np.exp(-(np.clip(np.abs(v) - TH / 2, 0, None) / 4.0) ** 2)
qf = (np.sqrt(3) / 3 * u - 1 / 3 * v) / S; rf = (2 / 3 * v) / S


def cube_round(q, r_):
    x_ = q; z_ = r_; y_ = -x_ - z_; rx, ry, rz = np.round(x_), np.round(y_), np.round(z_)
    dx, dy, dz = np.abs(rx - x_), np.abs(ry - y_), np.abs(rz - z_)
    m1 = (dx > dy) & (dx > dz); m2 = (~m1) & (dy > dz)
    rx = np.where(m1, -ry - rz, rx); ry = np.where(m2, -rx - rz, ry); rz = -rx - ry
    return rx, rz


hq, hr = cube_round(qf, rf)
cu = S * np.sqrt(3) * (hq + hr / 2); cv = S * 1.5 * hr
dcell = np.hypot(u - cu, v - cv) / S
hexedge = np.clip((dcell - 0.62) / 0.3, 0, 1) ** 1.5
# cell brightness varies per cell but must repeat every wedge: hash the cell index modulo the 5 periods
cell_rand = (np.sin(np.mod(hq + hr / 2, 5) * 12.9898 + hr * 78.233) * 43758.5453) % 1.0
# wedge mask: exact angular edges with a 1 px ramp (two neighbours sum to full)
edge_px = (half - np.abs(th)) * dr
wedge = np.clip(edge_px + 0.5, 0, 1)


def bake(ends, name):
    core = band * ends * (np.abs(v) < TH / 2 + 2)
    rim = np.exp(-((np.abs(v) - TH / 2) / 1.6) ** 2) * ends
    glow = np.exp(-np.clip(np.abs(v) - TH / 2, 0, None) / 14.0) * ends * 0.35
    al = np.clip(core * (0.16 + 0.10 * cell_rand + 0.75 * hexedge) + rim * 0.7 + glow, 0, 1) * wedge
    im = Image.fromarray((al * 255).astype(np.uint8), 'L')
    Image.merge('RGBA', (Image.new('L', im.size, 255),) * 3 + (im,)).save(
        os.path.join(ART, name + '.webp'), 'WEBP', lossless=True, quality=100, method=6, exact=True)


bake(np.ones_like(th), 'lev_anchor_seg')
# end wedge: fades out over the outer 60% toward +angle (mirrored in game for the other end)
t = (th + half) / (2 * half)
bake(np.clip((1.0 - t) / 0.6, 0, 1) ** 1.2, 'lev_anchor_end')
old = os.path.join(ART, 'lev_anchor_wall.webp')
if os.path.exists(old): os.remove(old)

java = '''package fr.testudo.spacecorsair.mod;

/** Generated by src/genanchor39.py (v39): Leviathan anchor wall placement, 1024 px hull-sprite units (+y = stern). */
final class ModAnchorData {
    private ModAnchorData() {}

    /** Wedge textures lev_anchor_seg / lev_anchor_end: W x H px; wedge centred on x 0 pointing to the prow, top edge at Y_TOP. */
    static final float W = %df, H = %df, Y_TOP = %sf;
    /** Arc radius around the hull centre, thickness, half-span (deg), wedge angle (deg), wedge count. */
    static final float R = %sf, TH = %sf, SPAN_DEG = %sf, SEG_DEG = %sf;
    static final int NSEG = %d;
}
''' % (W, H, round(y_top, 2), R, TH, SEG * NSEG / 2, SEG, NSEG)
open(os.path.join(HERE, 'java/fr/testudo/spacecorsair/mod/ModAnchorData.java'), 'w').write(java)
print('ok', W, H, round(y_top, 1), round(y_bot, 1), 'S', round(S, 2))
