# v38: bakes the Monolith s4/s5 effect data from the approved art (monolith-heat previews, owner 2026-11-02).
#   python3 -I src/genmono38.py work/modart
# Writes into work/modart (lossless WebP):
#   monolith_stage5_hull_hot, monolith_stage5_wingL_hot, monolith_stage5_wingR_hot, monolith_stage4_hot
#     = the sprite with its platinum plates heated to gold (drawn over the sprite with alpha = heat).
#   monolith_stage5_hull_aura, monolith_stage5_wingL_aura, monolith_stage5_wingR_aura, monolith_stage4_aura
#     = greyscale aura shell (soft glow + thin rim) around the silhouette, 512 px on a canvas AURA_PAD x the sprite.
# and src/java/.../ModMonoData.java: outline points + outward normals (ship-local 1024 px) and the wing trailing edge.
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

ART = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
AURA_PAD = 1.25


def load(n):
    return np.asarray(Image.open(os.path.join(ART, n + '.webp')).convert('RGBA')).astype(float)


def save(arr, n, mode='RGBA'):
    Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), mode).save(os.path.join(ART, n + '.webp'), 'WEBP', lossless=True, quality=100, method=6, exact=True)


def hot(x):
    mx = x[..., :3].max(-1); mn = x[..., :3].min(-1); lm = x[..., :3].mean(-1)
    plat = (x[..., 3] > 0) & ((mx - mn) < 35) & (lm > 90)
    h = x.copy(); s = np.clip(lm / 200, 0, 1.3)
    h[plat, 0] = np.clip(255 * s[plat], 0, 255); h[plat, 1] = np.clip(196 * s[plat], 0, 255); h[plat, 2] = np.clip(92 * s[plat], 0, 255)
    return h


def aura(x):
    n = x.shape[0]; P = int(round(n * AURA_PAD)); o = (P - n) // 2
    a = np.zeros((P, P), bool); a[o:o + n, o:o + n] = x[..., 3] > 40
    dist = ndimage.distance_transform_edt(~a)
    reach = n * 0.035   # ~36 px on the 1024 sprite (preview: 10-35 px on 400)
    soft = np.exp(-dist / reach) * (~a)
    rim = np.exp(-((dist - 2.5) ** 2) / 6.0) * (~a)
    v = np.clip(soft * 0.75 + rim * 0.9, 0, 1) * 255
    img = Image.fromarray(v.astype(np.uint8), 'L').resize((512, 512), Image.LANCZOS).convert('RGB')
    return np.asarray(img).astype(float)


def outline(x, count, step_from=None):
    """count points on the silhouette edge, evenly by arc angle around the centre, with outward normals."""
    a = ndimage.binary_opening(x[..., 3] > 40, iterations=2)
    edge = a & ~ndimage.binary_erosion(a)
    ys, xs = np.nonzero(edge)
    cy, cx = np.argwhere(a).mean(0)
    ang = np.arctan2(ys - cy, xs - cx)
    d = ndimage.distance_transform_edt(~a)
    gy, gx = np.gradient(ndimage.gaussian_filter(d, 4))
    pts = []
    for k in range(count):
        t = -np.pi + (k + 0.5) * 2 * np.pi / count
        sel = np.abs(np.angle(np.exp(1j * (ang - t)))) < np.pi / count
        if not sel.any(): continue
        r = np.hypot(ys[sel] - cy, xs[sel] - cx); i = np.argmax(r)
        px, py = xs[sel][i], ys[sel][i]
        # normal: gradient of the outside distance field a few px outside the edge
        ox, oy = px + (px - cx) / max(r[i], 1) * 5, py + (py - cy) / max(r[i], 1) * 5
        ox = int(np.clip(ox, 0, x.shape[1] - 1)); oy = int(np.clip(oy, 0, x.shape[0] - 1))
        nx, ny = gx[oy, ox], gy[oy, ox]; ln = np.hypot(nx, ny)
        if ln < 1e-6: nx, ny, ln = px - cx, py - cy, max(r[i], 1)
        pts += [int(px), int(py), round(float(nx / ln), 3), round(float(ny / ln), 3)]
    return pts


hull = load('monolith_stage5_hull'); wl = load('monolith_stage5_wingL'); wr = load('monolith_stage5_wingR'); s4 = load('monolith_stage4')
for src, n in ((hull, 'monolith_stage5_hull'), (wl, 'monolith_stage5_wingL'), (wr, 'monolith_stage5_wingR'), (s4, 'monolith_stage4')):
    save(hot(src), n + '_hot')
    save(aura(src), n + '_aura', 'RGB')

# wing trailing edge (preview plasma_wings.py _TE): tip, then the inner edge at y 690/600/505/410
wm = wl[..., 3] > 64
def inner(y): return int(np.where(wm[y])[0].max()) - 8
TE = [325, 782] + sum([[inner(y), y] for y in (690, 600, 505, 410)], [])

def jarr(v, f=False):
    return ', '.join(('%sf' % x) if f else str(x) for x in v)

