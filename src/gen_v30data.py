# v30: ChatGPT bosses_v30.json + derelicts.json -> ModV30Data.java (EN + ES string tables).
import json, sys
B = json.load(open(sys.argv[1], encoding='utf-8'))
D = json.load(open(sys.argv[2], encoding='utf-8'))
out = sys.argv[3]
q = lambda s: json.dumps(s, ensure_ascii=True)
BOSS = ['matriarch', 'guardian', 'empress']            # ModBoss.MATRIARCH, GUARDIAN, EMPRESS
TITAN = ['spartan', 'reaver', 'kretari', 'varn', 'ironclad', 'helion', 'warden']   # ModCapitals.FACTIONS order
def unit(u):
    sk = u['signature_skills']
    en = [u['name'], u['enrage']['name']] + u['enrage']['callout'] + sum([[s['name'], s['description']] for s in sk], [])
    es = [u['name'], u['enrage']['es']['name']] + u['enrage']['es']['callout'] + sum([[s['es']['name'], s['es']['description']] for s in sk], [])
    assert len(u['enrage']['callout']) == 2 and len(u['enrage']['es']['callout']) == 2
    return '{' + ', '.join(q(x) for x in en) + '}', '{' + ', '.join(q(x) for x in es) + '}'
L = ['package fr.testudo.spacecorsair.mod;', '',
     '/** Generated by src/gen_v30data.py from ChatGPT bosses_v30.json and derelicts.json. Do not edit. */',
     'final class ModV30Data {', '    private ModV30Data() {}', '',
     '    /** Per unit: name, enrage name, callout line 1, callout line 2, then (skill name, skill description) pairs. */']
for nm, keys, grp in (('BOSS', BOSS, 'bosses'), ('TITAN', TITAN, 'titans')):
    en, es = zip(*[unit(B[grp][k]) for k in keys])
    L.append('    static final String[][] %s_EN = {\n        %s};' % (nm, ',\n        '.join(en)))
    L.append('    static final String[][] %s_ES = {\n        %s};' % (nm, ',\n        '.join(es)))
S = D['sites']
for f in ('sector',):
    L.append('    static final String[] SITE_SECTOR = {%s};' % ', '.join(q(s['sector']) for s in S))
for f in ('event', 'history', 'scan_text', 'entry_line'):
    L.append('    static final String[][] SITE_%s = {\n        {%s},\n        {%s}};' % (f.upper(), ', '.join(q(s[f]) for s in S), ', '.join(q(s['es'][f]) for s in S)))
L.append('    static final String[][] SITE_HULLS = {%s};' % ', '.join('{' + ', '.join(q(w['hull']) for w in s['wrecks']) + '}' for s in S))
L.append('    static final int[][] SITE_COUNTS = {%s};' % ', '.join('{' + ', '.join(str(int(w['count'])) for w in s['wrecks']) + '}' for s in S))
L.append('}')
open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('sites', len(S))
