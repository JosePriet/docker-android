# v22 reputation content (ChatGPT, src/data/reputation.json) -> ModRepData.java
#   python3 -I src/genrep.py src/data/reputation.json src/java/fr/testudo/spacecorsair/mod/ModRepData.java
import json, sys
R = json.load(open(sys.argv[1]))
KEYS = ['spartan', 'reaver', 'kretari', 'varn', 'ironclad', 'helion', 'warden']
RANKS = ['Hostile', 'Unfriendly', 'Neutral', 'Friendly', 'Trusted', 'Honored']
FAM = {'railgun': 0, 'autocannon': 1, 'artillery': 2, 'blaster': 3, 'disintegrator': 4, 'arc': 5, 'arc projector': 5}
# names for the contract targets the text leaves generic (bounty target, station, escorted ship)
TARGET = {'spartan': ('Reaver Cutter', 'Reaver Listening Post', 'Republic ration hauler'),
          'reaver': ('Debt Marshal', 'Debt Marshal Tollhouse', 'Captured hauler'),
          'kretari': ('Syndicate Predator', 'Drilling Station', 'Brood carrier'),
          'varn': ('Contract Breaker', 'Rogue Relay', 'Varn vault transport'),
          'ironclad': ('Shift Raider', 'Raider Jammer', 'Evacuation shuttle'),
          'helion': ('Lane Raider', 'Raider Beacon', 'Helion courier'),
          'warden': ('Beacon Stalker', 'Pirate Relay', 'Relief hauler')}


def js(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


j = ['package fr.testudo.spacecorsair.mod;', '', '/** Generated by src/genrep.py from src/data/reputation.json (ChatGPT). Do not edit. */',
     'final class ModRepData {', '    private ModRepData() {}', '', '    static final String[] KEYS = {' + ', '.join(js(k) for k in KEYS) + '};',
     '    /** [faction][Hostile..Honored] */', '    static final String[][] RANKS = {']
for k in KEYS:
    j.append('        {' + ', '.join(js(R[k]['ranks'][r]) for r in RANKS) + '},')
j += ['    };', '    /** [faction][Friendly, Trusted, Honored] */', '    static final String[][] RANK_UP = {']
for k in KEYS:
    j.append('        {' + ', '.join(js(R[k]['rank_up'][r]) for r in RANKS[3:]) + '},')
j += ['    };', '    /** [faction][Unfriendly, Hostile] */', '    static final String[][] RANK_DOWN = {']
for k in KEYS:
    j.append('        {' + ', '.join(js(R[k]['rank_down'][r]) for r in ['Unfriendly', 'Hostile']) + '},')
j += ['    };', '    // faction, title, objective, briefing, success, amends, target name', '    static final Object[][] CONTRACTS = {']
for k in KEYS:
    for c in R[k]['contracts']:
        obj = c['objective']
        tn = TARGET[k][0] if obj == 'BOUNTY' else TARGET[k][1] if obj == 'DESTROY_STATION' else TARGET[k][2] if obj == 'ESCORT' else ''
        j.append('        {' + ', '.join([js(k), js(c['title']), js(obj), js(c['briefing']), js(c['success']), 'true' if c.get('amends') else 'false', js(tn)]) + '},')
j += ['    };', '    // name, family index, lore (one per faction, unlocked at Trusted)', '    static final Object[][] SECRET_WEAPON = {']
for k in KEYS:
    w = R[k]['secret_weapon']
    j.append('        {' + ', '.join([js(w['name']), str(FAM[w['family'].lower()]), js(w['lore'])]) + '},')
j += ['    };', '    // name, class, role, signature feature, lore (one per faction, unlocked at Honored; art in batch 2)', '    static final String[][] SECRET_SHIP = {']
for k in KEYS:
    s = R[k]['secret_ship']
    j.append('        {' + ', '.join(js(s[x]) for x in ['name', 'class', 'role', 'signature_feature', 'lore']) + '},')
j += ['    };', '}', '']
open(sys.argv[2], 'w').write('\n'.join(j))
print('contracts', sum(len(R[k]['contracts']) for k in KEYS))
