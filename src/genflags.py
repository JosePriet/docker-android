#!/usr/bin/env python3
"""v45: country flags for the multiplayer nickname screen.
Input: the unpacked npm package flag-icons (MIT, github.com/lipis/flag-icons) -> python3 src/genflags.py <package dir>
Output: work/modart/flags.webp (lossless atlas, 16 columns of 32x24 cells, ISO 3166-1 countries sorted by alpha-3)
        src/java/fr/testudo/spacecorsair/mod/ModFlagData.java (alpha-3 codes, English and Spanish names, same order)
Needs: cairosvg, pycountry, Pillow."""
import io, json, sys, gettext, os
import cairosvg, pycountry
from PIL import Image

pkg = sys.argv[1]
W, H, COLS = 32, 24, 16
es = gettext.translation('iso3166-1', pycountry.LOCALES_DIR, languages=['es'])
rows = []
for c in json.load(open(os.path.join(pkg, 'country.json'), encoding='utf-8')):
    if not c.get('iso'):
        continue
    pc = pycountry.countries.get(alpha_2=c['code'].upper())
    if pc is None:
        continue
    name = getattr(pc, 'common_name', None) or pc.name
    rows.append((pc.alpha_3, name, es.gettext(name), os.path.join(pkg, c['flag_4x3'])))
rows.sort()
atlas = Image.new('RGBA', (512, 512), (0, 0, 0, 0))   # power of two for GLES1
for i, (_, _, _, svg) in enumerate(rows):
    png = cairosvg.svg2png(url=svg, output_width=W * 4, output_height=H * 4)
    im = Image.open(io.BytesIO(png)).convert('RGBA').resize((W, H), Image.LANCZOS)
    atlas.paste(im, ((i % COLS) * W, (i // COLS) * H))
atlas.save('work/modart/flags.webp', lossless=True, quality=100, method=6)

def lit(v):
    return '"' + ''.join(ch if 32 <= ord(ch) < 127 and ch not in '"\\' else '\\u%04x' % ord(ch) for ch in v) + '"'

out = ['package fr.testudo.spacecorsair.mod;', '',
       '/** Generated by src/genflags.py (flag art: flag-icons, MIT licence, (c) Panayiotis Lipiridis). Do not edit. */',
       'final class ModFlagData {', '    private ModFlagData() {}', '',
       '    static final int W = %d, H = %d, COLS = %d;' % (W, H, COLS),
       '    /** ISO 3166-1 alpha-3, sorted; the index is the atlas cell. */',
       '    static final String[] CODES = {' + ', '.join(lit(r[0]) for r in rows) + '};',
       '    static final String[] EN = {' + ', '.join(lit(r[1]) for r in rows) + '};',
       '    static final String[] ES = {' + ', '.join(lit(r[2]) for r in rows) + '};',
       '}', '']
open('src/java/fr/testudo/spacecorsair/mod/ModFlagData.java', 'w', encoding='utf-8').write('\n'.join(out))
print(len(rows), 'flags', atlas.size)
