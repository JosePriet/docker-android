# v23: per-hull engine glow colours from the ChatGPT batch notes -> ModShipStyle.java
#   python3 -I src/genstyle.py src/data/notes_1.md src/java/fr/testudo/spacecorsair/mod/ModShipStyle.java
import re, sys
rows = []
for m in re.finditer(r"`((?:secret_)?\w+?)(?:_v2)?\.png` — .*?engine glow: `#([0-9A-Fa-f]{6})`", open(sys.argv[1]).read()):
    rows.append((m.group(1), m.group(2)))
j = ['package fr.testudo.spacecorsair.mod;', '', '/** Generated by src/genstyle.py from the ChatGPT batch notes: engine glow colour per hull art. */',
     'final class ModShipStyle {', '    private ModShipStyle() {}', '',
     '    static final String[] ARTS = {' + ', '.join('"%s"' % a for a, _ in rows) + '};',
     '    static final int[] ENGINE = {' + ', '.join('0x%s' % c.upper() for _, c in rows) + '};', '',
     '    static int engine(String art) {', '        for (int i = 0; i < ARTS.length; i++) if (ARTS[i].equals(art)) return ENGINE[i];', '        return -1;', '    }', '}', '']
open(sys.argv[2], 'w').write('\n'.join(j))
print(len(rows), rows[:3])
