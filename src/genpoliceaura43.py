# v43: police aura masks + hull outline points for the animated auras (ModPoliceAura, owner 2026-11-04 04:03).
#   python3 -I src/genpoliceaura43.py work/modart src/police42_arts.txt
# Per police hull of an aura faction (spartan, reaver, helion, warden, kretari) and every flagship:
#   mfx_pa_<art>.webp  256 px alpha mask: the hull silhouette dilated + blurred, on a canvas (1 + 2*PAD) x the sprite.
#   src/java/.../ModPoliceEdges.java: 40 outline points per art (sprite units, -0.5..0.5, +y = stern).
# Plus polfx_drop (RGBA white) (2x2 blood blob tiles). Lossless WebP; mfx_* load as GL_ALPHA (ModArt).
import os, sys, math
import numpy as np
from PIL import Image, ImageFilter, ImageDraw
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genpolice42 as g
import genpolice43 as g3

PAD = 0.18
C = 256
NPTS = 40
AURA_FACS = ('spartan', 'reaver', 'helion', 'warden', 'kretari')


def src_of(art, a):
    if a in g.STAGE5 and g.load(art, a + '_stage5') is not None:
        return a + '_stage5'
    return a


def mask_and_edges(art, a):
    im = g.load(art, src_of(art, a)).convert('RGBA')
    al = np.asarray(im)[..., 3]
    h, w = al.shape
    inner = int(round(C / (1 + 2 * PAD)))
    sil = Image.fromarray(((al > 32) * 255).astype(np.uint8), 'L').resize((inner, inner), Image.LANCZOS)
    can = Image.new('L', (C, C), 0)
    o = (C - inner) // 2
    can.paste(sil, (o, o))
    can = can.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(C * 0.035))
    m = np.asarray(can, float)
    m = m / max(m.max(), 1) * 255
    out = np.zeros((C, C, 4), np.uint8)
    out[..., :3] = 255
    out[..., 3] = np.clip(np.round(m), 0, 255).astype(np.uint8)
    g.save(Image.fromarray(out, 'RGBA'), art, 'mfx_pa_' + a)
    # outline points: farthest hull pixel along NPTS rays from the centroid
    ys, xs = np.nonzero(al > 32)
    cy, cx = ys.mean(), xs.mean()
    pts = []
    for i in range(NPTS):
        t = 2 * math.pi * i / NPTS
        dx, dy = math.sin(t), -math.cos(t)
        best = (cx, cy)
        r = 0.0
        while True:
            x, y = cx + dx * r, cy + dy * r
            if x < 0 or y < 0 or x >= w or y >= h:
                break
            if al[int(y), int(x)] > 32:
                best = (x, y)
            r += 1.0
        pts += [round(best[0] / w - 0.5, 3), round(best[1] / h - 0.5, 3)]
    return pts


def drop(art):
    S = 128
    can = Image.new('L', (S, S), 0)
    d = ImageDraw.Draw(can)
    rng = np.random.RandomState(7)
    for k in range(4):
        ox, oy = (k % 2) * 64 + 32, (k // 2) * 64 + 32
        for _ in range(5):
            r = rng.uniform(6, 14)
            x, y = ox + rng.uniform(-9, 9), oy + rng.uniform(-9, 9)
            d.ellipse([x - r, y - r, x + r, y + r], fill=255)
        for _ in range(3):           # small satellite drops
            r = rng.uniform(2, 4)
            a = rng.uniform(0, 6.28); dd = rng.uniform(16, 24)
            x, y = ox + math.cos(a) * dd, oy + math.sin(a) * dd
            d.ellipse([x - r, y - r, x + r, y + r], fill=255)
    can = can.filter(ImageFilter.GaussianBlur(1.6))
    out = np.zeros((S, S, 4), np.uint8); out[..., :3] = 255; out[..., 3] = np.asarray(can)
    g.save(Image.fromarray(out, 'RGBA'), art, 'polfx_drop')


def main():
    art, lst = sys.argv[1], sys.argv[2]
    fac = g3.roster()
    arts = [l.strip() for l in open(lst) if l.strip() and not l.startswith('#')]
    todo = [a for a in arts if fac.get(a) in AURA_FACS] + ['cap_' + k for k in g.CAPS]
    lines = []
    for a in todo:
        p = mask_and_edges(art, a)
        lines.append('        E.put("%s", new float[] {%s});' % (a, ', '.join('%gf' % v for v in p)))
    drop(art)
    java = '''package fr.testudo.spacecorsair.mod;

import java.util.HashMap;

/** Generated by src/genpoliceaura43.py: hull outline points per police art (sprite units, -0.5..0.5, +y = stern). */
final class ModPoliceEdges {
    private ModPoliceEdges() { }

    static final float PAD = %sf;
    static final HashMap<String, float[]> E = new HashMap<String, float[]>();

    static {
%s
    }

    static float[] get(String art) {
        return E.get(art);
    }
}
''' % (PAD, '\n'.join(lines))
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'java/fr/testudo/spacecorsair/mod/ModPoliceEdges.java'), 'w').write(java)
    print(len(todo), 'masks')


if __name__ == '__main__':
    main()
