#!/usr/bin/env python3
"""Space Corsair v34 economy/XP simulation (standalone, no game edits).
Usage: python3 econ_sim.py [report_path]. Stdlib only. All assumptions are PARAMETERS below."""
import itertools, sys, os

# ---- stock facts (verified in ModQol.java: bounty 18*(lv+1)^2, elite x2, boss x8, missions x3, sell 0.25)
XP_STOCK = [1200,1300,1600,2800,4500,5000,8000,12000,15000,16000,18000,20000,22000,25000,29000,34000,37000]
CAP = 40
GROWTH = 0.08                 # owner A2: +8%/level above L17
# ---- player model parameters (assumptions)
P = dict(
    kills_h=40, elites_h=4, bosses_h=0.3,      # per hour at matched level
    xp_k=7.0, xp_p=1.5,                        # ASSUMED xp per normal kill = xp_k*(lv+1)^xp_p (not found in mod code)
    elite_xp=2.0, boss_xp=8.0,                 # xp multipliers vs normal kill (assumed = bounty multipliers)
    deaths_h=3, death_cap=0.15,                # B3
    missions_h=1.5, mission_base=3.0,          # stock mission reward = mission_base * bounty(lv) per mission
    gear_frac=0.5,                             # full gear fit cost = gear_frac * hull price (per class)
    resale=0.5,                                # previous hull resold at resale*price
)
# ship price targets (cheapest of class, from owner/task list) and ladder
SHIPS = [("cruiser",150e3),("battleship",1.1e6),("titan",6e6)]
TARGET_H = {"cruiser":2,"battleship":8,"titan":20}
# ---- tunables (the proposal)
TUNE_STOCK = dict(kb=1.0, bp=2.0, loot=0.0, mf=3.0)   # stock: 18*(lv+1)^2, no loot share, missions x3

def xp_table():
    t = list(XP_STOCK)
    for _ in range(18, CAP+1): t.append(t[-1]*(1+GROWTH))
    return t                                    # t[i] = XP to go from level i+1 to i+2 (len 40 -> L1..L40 entries)

def bounty(lv, T):  return 18*T["kb"]*(lv+1)**T["bp"]
def xp_kill(lv):    return P["xp_k"]*(lv+1)**P["xp_p"]

def income(lv, T):
    b = bounty(lv, T)
    kills = P["kills_h"]*b + P["elites_h"]*b*2 + P["bosses_h"]*b*8
    loot = T["loot"]*kills
    miss = P["missions_h"]*T["mf"]*b*P["mission_base"]/3.0*1.0
    return kills, loot, miss

def death_cost(lv, T):
    gross = sum(income(lv, T))
    raw = 2*18*(lv+1)**2                        # draft formula (not scaled by kb)
    cap = P["death_cap"]*gross/P["deaths_h"]
    return min(raw, cap), raw, cap, P["deaths_h"]*min(raw, cap)/gross

def xp_rate(lv):
    return xp_kill(lv)*(P["kills_h"]+P["elites_h"]*P["elite_xp"]+P["bosses_h"]*P["boss_xp"])

def simulate(T, dt=0.02, tmax=600, full=False):
    xt = xp_table(); lv, xp, t, cash = 1, 0.0, 0.0, 0.0
    lvl_h = {}; owned = 0.0; res = {}; i = 0
    while t < tmax and (i < len(SHIPS) or (full and lv < CAP)):
        if lv < CAP: 
            xp += xp_rate(lv)*dt
            while lv < CAP and xp >= xt[lv-1]:
                xp -= xt[lv-1]; lv += 1; lvl_h[lv] = t
        inc = sum(income(lv, T)) - P["deaths_h"]*death_cost(lv, T)[0]
        cash += inc*dt; t += dt
        if i >= len(SHIPS): continue
        name, price = SHIPS[i]
        cost = price*(1+P["gear_frac"]) - owned
        if cash >= cost:
            cash -= cost; owned = price*P["resale"]; res[name] = (t, lv); i += 1
    return res, lvl_h

def err(T):
    res, _ = simulate(T, dt=0.05)
    e = 0
    for n,_p in SHIPS:
        h = res.get(n, (400,0))[0]
        e += (h/TARGET_H[n]-1)**2
    return e

def tune():
    best = None
    for kb in [x/4 for x in range(2,81)]:
        for bp in (0.8,1.0,1.2,1.4,1.6,1.8,2.0,2.2):
            for loot in (0.3,0.5):
                for mf in (1.0,2.0,3.0):
                    T = dict(kb=kb,bp=bp,loot=loot,mf=mf)
                    k,l,m = income(15,T)
                    if not (k>l>m): continue          # G3 ordering kills > loot > missions
                    e = err(T)
                    if best is None or e < best[0]: best = (e,T)
    return best[1]

def fmt(n): return f"{n:,.0f}"

def main():
    out = sys.argv[1] if len(sys.argv)>1 else os.path.join(os.path.dirname(os.path.abspath(__file__)),"econ_report.md")
    T = tune(); S = TUNE_STOCK
    xt = xp_table()
    L = []
    tot = sum(xt[:CAP-1])
    L.append("# Space Corsair v34 economy sim (generated by econ_sim.py)")
    L.append(f"XP L1-17 stock sum {fmt(sum(XP_STOCK[:16]))} (+L17 {XP_STOCK[16]:,}); L18-40 at +8%/lvl; total XP to L40 = {fmt(tot)} (owner est ~1.4M).")
    L.append("L18-40 XP per level: " + ", ".join(f"L{i+1}:{xt[i]/1000:.1f}k" for i in range(17,CAP-1)))
    L.append("")
    L.append("## Assumptions (parameters in econ_sim.py)")
    L.append(f"- {P['kills_h']} kills/h, {P['elites_h']} elites/h, {P['bosses_h']} bosses/h at matched level; {P['deaths_h']} deaths/h; penalty 2*18*(lv+1)^2 capped at {int(P['death_cap']*100)}% of hourly income.")
    L.append(f"- XP per normal kill ASSUMED = {P['xp_k']}*(lv+1)^{P['xp_p']} (real value not in mod code); elite x{P['elite_xp']}, boss x{P['boss_xp']}.")
    L.append(f"- Missions {P['missions_h']}/h, each worth {P['mission_base']:.0f} kill-bounties before the mission factor; loot income = share of kill income (sold at 25%).")
    L.append(f"- Gear fit = {P['gear_frac']:.0%} of hull price per class; previous hull resold at {P['resale']:.0%}; cash accumulates across the ladder cruiser > battleship > titan (cheapest of class: 150k / 1.1M / 6M).")
    L.append("")
    for label, TT in (("STOCK-curve (18*(lv+1)^2, missions x3, loot share 0)", S), ("PROPOSED tuned", T)):
        res, lh = simulate(TT)
        L.append(f"## Result: {label}")
        L.append("| Milestone | Target h | Sim h | Level then |"); L.append("|---|---|---|---|")
        for n,_p in SHIPS:
            r = res.get(n)
            L.append(f"| first {n} (+gear) | {TARGET_H[n]} | {r[0]:.1f} | L{r[1]} |" if r else f"| first {n} | {TARGET_H[n]} | >400 | - |")
        L.append("")
    res, lh = simulate(T, full=True)
    L.append("## Per-level table, proposed curve")
    L.append("| Lv | hours to reach | kill c/h | loot c/h | mission c/h | total c/h | death fee | 3 deaths % income |")
    L.append("|---|---|---|---|---|---|---|---|")
    for lv in (2,5,8,10,13,15,17,20,25,30,35,40):
        k,l,m = income(lv,T); d,raw,cap,pct = death_cost(lv,T)
        L.append(f"| {lv} | {lh.get(lv,float('nan')):.1f} | {fmt(k)} | {fmt(l)} | {fmt(m)} | {fmt(k+l+m)} | {fmt(d)}{' (capped)' if cap<raw else ''} | {pct*100:.1f}% |")
    worst = max(death_cost(lv,T)[3] for lv in range(1,CAP+1))
    L.append(f"\nDeath-penalty check (3 deaths <= 15% of income): worst level = {worst*100:.1f}% -> {'PASS' if worst<=0.1501 else 'FAIL'}. "
             f"Uncapped draft formula would exceed 15% at levels: " +
             (", ".join(str(lv) for lv in range(1,CAP+1) if death_cost(lv,T)[1]*3 > 0.15*sum(income(lv,T))) or "none") + ".")
    k,l,m = income(15,T); L.append(f"Ordering check at L15: kills {fmt(k)} > loot {fmt(l)} > missions {fmt(m)}: {'PASS' if k>l>m else 'FAIL'}.")
    L.append("")
    L.append("## Proposed constants")
    L.append("```")
    L.append(f"BOUNTY_COEF   = {18*T['kb']:.2f}      # was 18   -> bounty = coef*(lv+1)^exp, elite x2, boss x8 unchanged")
    L.append(f"BOUNTY_EXP    = {T['bp']}       # was 2.0")
    L.append(f"LOOT_SHARE    = {T['loot']}       # loot sale value ~ share of kill income (ordering kills>loot>missions)")
    L.append(f"MISSION_MULT  = {T['mf']}       # was x3 (ModQol.missionCredits)")
    L.append("DEATH_PENALTY = min(2*18*(lv+1)^2, 0.15*hourly_income(lv)/3)")
    L.append("```")
    L.append("Caveat: XP/kill and loot/mission volumes are assumed; re-fit after one emulator/phone measurement of kills/h and credits/h.")
    open(out,"w").write("\n".join(L)+"\n")
    print("\n".join(L[:0]) or f"wrote {out}"); print(T)
main()
